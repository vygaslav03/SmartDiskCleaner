LANGS = {"ru": RU, "uk": UK, "en": EN}


def set_language(code: str) -> None:
    global _current
    _current = code if code in LANGS else "ru"


def current_language() -> str:
    return _current


def tr(key: str, **params) -> str:
    """Перевод ключа. Недостающие строки берутся из русского, затем английского словаря."""
    text = LANGS.get(_current, RU).get(key)
    if text is None:
        text = RU.get(key) if _current != "en" else EN.get(key)
    if text is None:
        text = EN.get(key) or RU.get(key) or key
    if params:
        try:
            return text.format(**params)
        except (KeyError, IndexError, ValueError):
            return text
    return text
